-- SOS rápido: reflexões OPCIONAIS, associadas somente ao usuário autenticado.
-- A ajuda imediata não depende desta tabela, de login ou de conexão.
CREATE TABLE IF NOT EXISTS public.sos_quick_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  feeling text NOT NULL CHECK (feeling IN ('urge','anxiety','irritation','sleep')),
  intensity_before smallint NULL CHECK (intensity_before BETWEEN 0 AND 10),
  intensity_after smallint NULL CHECK (intensity_after BETWEEN 0 AND 10),
  duration_seconds integer NOT NULL CHECK (duration_seconds BETWEEN 0 AND 3600),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sos_quick_sessions_user_created_idx
  ON public.sos_quick_sessions (user_id, created_at DESC);
ALTER TABLE public.sos_quick_sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.sos_quick_sessions FROM PUBLIC, anon;
GRANT SELECT, INSERT, DELETE ON TABLE public.sos_quick_sessions TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.sos_quick_sessions_id_seq TO authenticated;
DO $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='sos_quick_sessions' AND policyname='quick_sos_select_own') THEN
  CREATE POLICY quick_sos_select_own ON public.sos_quick_sessions FOR SELECT TO authenticated USING ((SELECT auth.uid())=user_id);
 END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='sos_quick_sessions' AND policyname='quick_sos_insert_own') THEN
  CREATE POLICY quick_sos_insert_own ON public.sos_quick_sessions FOR INSERT TO authenticated WITH CHECK ((SELECT auth.uid())=user_id);
 END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='sos_quick_sessions' AND policyname='quick_sos_delete_own') THEN
  CREATE POLICY quick_sos_delete_own ON public.sos_quick_sessions FOR DELETE TO authenticated USING ((SELECT auth.uid())=user_id);
 END IF;
END $$;
COMMENT ON TABLE public.sos_quick_sessions IS 'Registros opcionais SOS rápido salvos apenas quando usuário pede; não atribui pontos nem recompensas.';
